import React, { useState } from 'react';
import {
  CheckCircle2,
  AlertTriangle,
  OctagonAlert,
  WifiOff,
  Wifi,
  FlaskConical,
  Cpu,
  Radio,
  HelpCircle,
  Sparkles,
} from 'lucide-react';
import { DataSourceType, ReadingDataSource } from '../types/index';
import { getDataSourceLabel } from '../utils/formatters';

export const StatusBadge: React.FC<{
  status: string;
  size?: 'sm' | 'md';
  customLabel?: string;
}> = ({ status, size = 'sm', customLabel }) => {
  const normalized = (status || 'normal').toLowerCase();
  const baseClasses =
    size === 'sm'
      ? 'inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-semibold border'
      : 'inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-semibold border';

  if (normalized === 'critical') {
    return (
      <span
        className={`${baseClasses} bg-red-50 text-red-700 border-red-200 dark:bg-red-950/60 dark:text-red-300 dark:border-red-800/80`}
      >
        <OctagonAlert className="w-3.5 h-3.5 shrink-0" aria-hidden="true" />
        <span>{customLabel || 'Critical'}</span>
      </span>
    );
  }

  if (normalized === 'warning') {
    return (
      <span
        className={`${baseClasses} bg-amber-50 text-amber-800 border-amber-200 dark:bg-amber-950/60 dark:text-amber-300 dark:border-amber-800/80`}
      >
        <AlertTriangle className="w-3.5 h-3.5 shrink-0" aria-hidden="true" />
        <span>{customLabel || 'Warning'}</span>
      </span>
    );
  }

  if (normalized === 'offline' || normalized === 'fault' || normalized === 'missing') {
    return (
      <span
        className={`${baseClasses} bg-slate-100 text-slate-700 border-slate-300 dark:bg-slate-800 dark:text-slate-300 dark:border-slate-700`}
      >
        <WifiOff className="w-3.5 h-3.5 shrink-0" aria-hidden="true" />
        <span>{customLabel || (normalized === 'offline' ? 'Offline' : 'No Data')}</span>
      </span>
    );
  }

  return (
    <span
      className={`${baseClasses} bg-emerald-50 text-emerald-700 border-emerald-200 dark:bg-emerald-950/60 dark:text-emerald-300 dark:border-emerald-800/80`}
    >
      <CheckCircle2 className="w-3.5 h-3.5 shrink-0" aria-hidden="true" />
      <span>{customLabel || 'Normal'}</span>
    </span>
  );
};

